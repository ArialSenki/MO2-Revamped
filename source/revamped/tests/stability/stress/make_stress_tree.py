"""A big fake Skyrim SE instance for the stability stress run (test only).

    py -3.12 -I make_stress_tree.py <root> [mods]

1500 mods by default: one plugin each (every tenth also a master-flagged one),
pairs of mods sharing a plugin name, and a few loose files each. All active.
"""
import os
import shutil
import struct
import sys


def plugin(master=False, light=False):
    hedr = b"HEDR" + struct.pack("<H", 12) + struct.pack("<fiI", 1.71, 1, 0x800)
    flags = (1 if master else 0) | (0x200 if light else 0)
    return b"TES4" + struct.pack("<IIIIHH", len(hedr), flags, 0, 0, 44, 0) + hedr


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)


def main():
    root = sys.argv[1]
    count = int(sys.argv[2]) if len(sys.argv) > 2 else 1500
    if os.path.exists(root):
        shutil.rmtree(root)
    game, inst = os.path.join(root, "game"), os.path.join(root, "instance")
    os.makedirs(game)
    shutil.copy(os.path.join(os.environ["SystemRoot"], "System32", "whoami.exe"),
                os.path.join(game, "SkyrimSE.exe"))
    for name in ("Skyrim.esm", "Update.esm", "Dawnguard.esm", "HearthFires.esm", "Dragonborn.esm"):
        write(os.path.join(game, "Data", name), plugin(master=True))
    write(os.path.join(game, "Skyrim.ccc"), b"")

    mods, lines = [], []
    for m in range(count):
        mod = f"Stress {m:04d}"
        files = [(f"stress_{m:04d}.esp", plugin(light=(m % 7 == 0)))]
        if m % 10 == 0:
            files.append((f"stress_{m:04d}_master.esp", plugin(master=True)))
        if m < 100:
            files.append((f"shared_{m // 2:02d}.esp", plugin()))
        for j in range(5):
            files.append((f"meshes/stress/{m:04d}/part{j}.nif", b"nif" * 10))
        files.append(("textures/stress/common.dds", b"DDS " + bytes(124)))
        mods.append((mod, files))
        lines.extend("*" + name for name, _ in files if name.endswith(".esp") and "/" not in name)
    for mod, files in mods:
        for name, data in files:
            write(os.path.join(inst, "mods", mod, name), data)
        with open(os.path.join(inst, "mods", mod, "meta.ini"), "w") as f:
            f.write("[General]\nmodid=0\nversion=1.0\n")

    prof = os.path.join(inst, "profiles", "Default")
    os.makedirs(prof)
    with open(os.path.join(prof, "modlist.txt"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write("".join(f"+{mod}\n" for mod, _ in mods))
    seen, unique = set(), []
    for line in lines:
        if line.lower() not in seen:
            seen.add(line.lower())
            unique.append(line)
    with open(os.path.join(prof, "plugins.txt"), "w", encoding="mbcs", newline="\r\n") as f:
        f.write("# This file was automatically generated by Mod Organizer.\n"
                + "".join(l + "\n" for l in unique))
    with open(os.path.join(prof, "settings.ini"), "w") as f:
        f.write("[General]\nLocalSaves=false\nLocalSettings=true\nAutomaticArchiveInvalidation=false\n")
    for ini in ("skyrim.ini", "skyrimprefs.ini", "skyrimcustom.ini"):
        open(os.path.join(prof, ini), "w").close()
    for folder in ("downloads", "overwrite"):
        os.makedirs(os.path.join(inst, folder), exist_ok=True)
    with open(os.path.join(inst, "ModOrganizer.ini"), "w") as f:
        f.write("[General]\ngameName=Skyrim Special Edition\ngamePath=@ByteArray("
                + game.replace("\\", "\\\\")
                + ")\ngame_edition=Steam\nselected_profile=@ByteArray(Default)\nfirst_start=false\n")
    print(f"{len(unique)} plugins in {len(mods)} mods")


if __name__ == "__main__":
    main()
