"""Fake game trees for the Bethesda golden tests (MO2 Revamped).

    python -I make_tree.py <root> <case> [<game>]

<game> is skyrimse (the default) or falloutnv. Writes <root>/game (a fake
game: the exe is any exe, Data has the masters) and <root>/instance (mods,
profile Default, ModOrganizer.ini). Nothing outside <root> is touched.

New Vegas orders plugins by file time, so every plugin and profile file gets
an explicit modification time and the result doesn't depend on when the tree
was made.
"""
import os
import shutil
import struct
import sys

# 2010-10-19 00:00 UTC, New Vegas' release; every New Vegas time is an offset of it
T0 = 1287446400
HOUR = 3600


def plugin(master=False, light=False, version=1.71, form=44):
    """A TES4 header record. Skyrim SE: HEDR 1.71, form version 44; FO3/NV: 1.34 and 15."""
    hedr = b"HEDR" + struct.pack("<H", 12) + struct.pack("<fiI", version, 1, 0x800)
    flags = (1 if master else 0) | (0x200 if light else 0)
    return b"TES4" + struct.pack("<IIIIHH", len(hedr), flags, 0, 0, form, 0) + hedr


def nv(master=False):
    return plugin(master=master, version=1.34, form=15)


def write(path, data, mtime=None):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)
    if mtime is not None:
        os.utime(path, (mtime, mtime))


def at(hours):
    return T0 + hours * HOUR


# ---------------------------------------------------------------- Skyrim SE

def skyrimse_case(case):
    """[(mod, [(file, bytes)])] by priority, highest first, and the plugins.txt lines."""
    if case == "big":
        mods = [(f"Filler {m:02d}", [(f"filler_{m:02d}_{i:03d}.esp", plugin()) for i in range(100)])
                for m in range(40)]
        lines = [f"*filler_{m:02d}_{i:03d}.esp" for m in range(40) for i in range(100)]
        return mods, lines
    if case == "case":
        mods = [("Case Winner", [("Case Test Plugin.esp", plugin())]),
                ("Case Loser", [("case test plugin.esp", plugin())])]
        return mods, ["*case test plugin.esp"]
    if case == "unicode":
        mods = [("Unicode", [("Ñandú Armería.esp", plugin()), ("Café Señal.esl", plugin(light=True))])]
        return mods, ["*Ñandú Armería.esp", "*Café Señal.esl"]
    if case == "mixed":
        mods = [("Mixed", [("Active.esp", plugin()), ("Inactive.esp", plugin()), ("Flagged Light.esp", plugin(light=True)),
                           ("Ext Light.esl", plugin(master=True, light=True)), ("Master.esm", plugin(master=True))])]
        # a primary plugin with and without '*', an unknown plugin, a comment and a blank line
        lines = ["# comment", "*Skyrim.esm", "Update.esm", "*Master.esm", "*Active.esp", "Inactive.esp",
                 "*Missing.esp", "", "*Flagged Light.esp", "*Ext Light.esl"]
        return mods, lines
    raise SystemExit(f"unknown case {case}")


def skyrimse(root, case):
    game, inst = os.path.join(root, "game"), os.path.join(root, "instance")
    shutil.copy(os.path.join(os.environ["SystemRoot"], "System32", "whoami.exe"), os.path.join(os.makedirs(game) or game, "SkyrimSE.exe"))
    for name in ("Skyrim.esm", "Update.esm", "Dawnguard.esm", "HearthFires.esm", "Dragonborn.esm"):
        write(os.path.join(game, "Data", name), plugin(master=True))
    write(os.path.join(game, "Skyrim.ccc"), b"")
    mods, lines = skyrimse_case(case)
    for mod, files in mods:
        for name, data in files:
            write(os.path.join(inst, "mods", mod, name), data)
    prof = os.path.join(inst, "profiles", "Default")
    os.makedirs(prof)
    with open(os.path.join(prof, "modlist.txt"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write("".join(f"+{mod}\n" for mod, _ in mods))
    # plugins.txt is in the system code page, as the game and MO2 write it
    with open(os.path.join(prof, "plugins.txt"), "w", encoding="mbcs", newline="\r\n") as f:
        f.write("# This file was automatically generated by Mod Organizer.\n" + "".join(l + "\n" for l in lines))
    with open(os.path.join(prof, "settings.ini"), "w") as f:
        f.write("[General]\nLocalSaves=false\nLocalSettings=true\nAutomaticArchiveInvalidation=false\n")
    for ini in ("skyrim.ini", "skyrimprefs.ini", "skyrimcustom.ini"):
        open(os.path.join(prof, ini), "w").close()
    with open(os.path.join(inst, "ModOrganizer.ini"), "w") as f:
        f.write("[General]\ngameName=Skyrim Special Edition\ngamePath=@ByteArray(" + game.replace("\\", "\\\\")
                + ")\ngame_edition=Steam\nselected_profile=@ByteArray(Default)\nfirst_start=false\n")
    print(f"{case}: {sum(len(f) for _, f in mods)} plugins in {len(mods)} mods")


# ---------------------------------------------------------------- New Vegas

NV_PRIMARY = "FalloutNV.esm"
# gamefalloutnv.cpp DLCPlugins(), in its order
NV_DLC = ["DeadMoney.esm", "HonestHearts.esm", "OldWorldBlues.esm", "LonesomeRoad.esm",
          "GunRunnersArsenal.esm", "CaravanPack.esm", "ClassicPack.esm", "MercenaryPack.esm",
          "TribalPack.esm"]
# Data folder times, hours after T0: not in DLCPlugins() order (Gun Runners'
# Arsenal is older than Dead Money, the packs are interleaved)
NV_DATA_TIMES = {"FalloutNV.esm": 0, "GunRunnersArsenal.esm": 9, "DeadMoney.esm": 10,
                 "HonestHearts.esm": 11, "ClassicPack.esm": 12, "OldWorldBlues.esm": 13,
                 "LonesomeRoad.esm": 14, "CaravanPack.esm": 15, "TribalPack.esm": 16,
                 "MercenaryPack.esm": 17}
MO2_HEADER = "# This file was automatically generated by Mod Organizer."


def falloutnv_case(case):
    """Returns (mods, plugins.txt lines, loadorder.txt lines or None, plugins.txt time,
    loadorder.txt time). mods are [(mod, [(file, bytes, mtime)])] by priority, highest
    first."""
    profile_time = at(24 * 400)
    all_dlc = [NV_PRIMARY] + NV_DLC
    if case == "mtime":
        # no loadorder.txt: the order is the file times alone, masters and plugins
        # mixed (an .esp older than the DLC and than a master in a mod)
        mods = [("Late Master", [("Late Master.esm", nv(True), at(100))]),
                ("Patches", [("Zeta Patch.esp", nv(), at(20)), ("Alpha Patch.esp", nv(), at(90))]),
                ("Early Plugin", [("Early Plugin.esp", nv(), at(5))]),
                ("Middle", [("Middle.esp", nv(), at(50)), ("Middle Master.esm", nv(True), at(60))])]
        lines = all_dlc + ["Late Master.esm", "Alpha Patch.esp", "Early Plugin.esp", "Middle.esp",
                           "Middle Master.esm"]
        return mods, lines, None, profile_time, None
    if case in ("disagree", "disagree-old"):
        # loadorder.txt against the file times: C, B, A by the list, A, B, C by
        # time; the primary plugin in the middle; a plugin not in the list and one in
        # the list that doesn't exist; only some DLC listed. "disagree" has
        # loadorder.txt newer than plugins.txt, "disagree-old" older.
        mods = [("Order", [("A.esp", nv(), at(30)), ("B.esp", nv(), at(31)), ("C.esp", nv(), at(32)),
                           ("D.esm", nv(True), at(33)), ("Unlisted.esp", nv(), at(1))])]
        order = [MO2_HEADER, "C.esp", "DeadMoney.esm", "B.esp", "FalloutNV.esm", "Gone.esp", "A.esp",
                 "D.esm", "HonestHearts.esm"]
        lines = [NV_PRIMARY, "DeadMoney.esm", "HonestHearts.esm", "A.esp", "B.esp", "C.esp", "D.esm",
                 "Unlisted.esp", "Gone.esp"]
        lo_time = profile_time + (HOUR if case == "disagree" else -HOUR)
        return mods, lines, order, profile_time, lo_time
    if case == "mixed":
        # plugins.txt as people leave it: a comment, the primary plugin in lower
        # case, a missing plugin, a blank line, Skyrim's '*', spaces around a name,
        # the same plugin twice with different case; Inactive.esp and most DLC
        # absent (inactive)
        mods = [("Mixed", [("Active.esp", nv(), at(40)), ("Inactive.esp", nv(), at(41)),
                           ("Starred.esp", nv(), at(42)), ("Dupe.esp", nv(), at(43)),
                           ("Master.esm", nv(True), at(44)), ("Spaced.esp", nv(), at(45))])]
        lines = ["# comment", "falloutnv.esm", "DeadMoney.esm", "Active.esp", "Missing.esp", "",
                 "*Starred.esp", "  Spaced.esp  ", "dupe.esp", "Dupe.esp", "Master.esm"]
        return mods, lines, None, profile_time, None
    if case == "unicode":
        # names in CP-1252 outside ASCII, two of them (Œ, €) outside Latin-1;
        # loadorder.txt is UTF-8 and leaves one out
        mods = [("Unicode", [("Ñandú Armería.esp", nv(), at(30)), ("Café Señal.esm", nv(True), at(31)),
                             ("Œuvre €uro.esp", nv(), at(29)), ("Ægis Ünïcode.esp", nv(), at(32))])]
        order = [MO2_HEADER, "FalloutNV.esm", "Café Señal.esm", "Œuvre €uro.esp", "Ñandú Armería.esp"]
        lines = [NV_PRIMARY, "Ñandú Armería.esp", "Café Señal.esm", "Ægis Ünïcode.esp"]
        return mods, lines, order, profile_time, profile_time + HOUR
    if case == "case":
        # one plugin in two mods with different case and different times: the
        # winner's time puts it after Other.esp, the loser's would put it first
        mods = [("Case Winner", [("Case Test Plugin.esp", nv(), at(40))]),
                ("Other", [("Other.esp", nv(), at(20))]),
                ("Case Loser", [("case test plugin.esp", nv(), at(2))])]
        lines = [NV_PRIMARY, "CASE TEST PLUGIN.ESP", "Other.esp"]
        return mods, lines, None, profile_time, None
    if case == "big":
        # 4,000 plugins, no loadorder.txt: the times are a permutation of the
        # names (k * 7919 mod 4000, a minute apart), every fifth one inactive
        mods, lines = [], [NV_PRIMARY] + NV_DLC
        for m in range(40):
            files = []
            for i in range(100):
                k = m * 100 + i
                name = f"filler_{m:02d}_{i:03d}.esp"
                files.append((name, nv(), at(24 * 30) + ((k * 7919) % 4000) * 60))
                if k % 5 != 4:
                    lines.append(name)
            mods.append((f"Filler {m:02d}", files))
        return mods, lines, None, profile_time, None
    raise SystemExit(f"unknown case {case}")


def falloutnv(root, case):
    game, inst = os.path.join(root, "game"), os.path.join(root, "instance")
    os.makedirs(game)
    shutil.copy(os.path.join(os.environ["SystemRoot"], "System32", "whoami.exe"), os.path.join(game, "FalloutNV.exe"))
    for name in [NV_PRIMARY] + NV_DLC:
        write(os.path.join(game, "Data", name), nv(master=True), at(NV_DATA_TIMES[name]))
    mods, lines, order, plugins_time, order_time = falloutnv_case(case)
    for mod, files in mods:
        for name, data, mtime in files:
            write(os.path.join(inst, "mods", mod, name), data, mtime)
    prof = os.path.join(inst, "profiles", "Default")
    os.makedirs(prof)
    with open(os.path.join(prof, "modlist.txt"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write("".join(f"+{mod}\n" for mod, _ in mods))
    # plugins.txt in the system code page, loadorder.txt in UTF-8, as MO2 writes them
    path = os.path.join(prof, "plugins.txt")
    with open(path, "w", encoding="mbcs", newline="\r\n") as f:
        f.write(MO2_HEADER + "\n" + "".join(l + "\n" for l in lines))
    os.utime(path, (plugins_time, plugins_time))
    if order is not None:
        path = os.path.join(prof, "loadorder.txt")
        with open(path, "w", encoding="utf-8", newline="\r\n") as f:
            f.write("".join(l + "\n" for l in order))
        os.utime(path, (order_time, order_time))
    with open(os.path.join(prof, "settings.ini"), "w") as f:
        f.write("[General]\nLocalSaves=false\nLocalSettings=true\nAutomaticArchiveInvalidation=false\n")
    # gamefalloutnv.cpp iniFiles(); present so MO2 copies nothing from My Games
    for ini in ("fallout.ini", "falloutprefs.ini", "falloutcustom.ini", "GECKCustom.ini", "GECKPrefs.ini"):
        open(os.path.join(prof, ini), "w").close()
    with open(os.path.join(inst, "ModOrganizer.ini"), "w") as f:
        f.write("[General]\ngameName=New Vegas\ngamePath=@ByteArray(" + game.replace("\\", "\\\\")
                + ")\ngame_edition=Steam\nselected_profile=@ByteArray(Default)\nfirst_start=false\n")
    print(f"falloutnv {case}: {sum(len(f) for _, f in mods)} plugins in {len(mods)} mods"
          f"{'' if order is None else ', with loadorder.txt'}")


GAMES = {"skyrimse": skyrimse, "falloutnv": falloutnv}


def main():
    if len(sys.argv) not in (3, 4) or (len(sys.argv) == 4 and sys.argv[3] not in GAMES):
        raise SystemExit(__doc__)
    root, case = sys.argv[1], sys.argv[2]
    game = sys.argv[3] if len(sys.argv) == 4 else "skyrimse"
    if os.path.exists(root):
        shutil.rmtree(root)
    GAMES[game](root, case)


if __name__ == "__main__":
    main()
