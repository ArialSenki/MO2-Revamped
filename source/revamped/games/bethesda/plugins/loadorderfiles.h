// The text formats of the profile's plugin lists, as MO2 has always written
// them (the golden files in source/revamped/tests/bethesda/golden are the
// contract):
// - plugins.txt is in the system ANSI code page, CRLF, with MO2's header line.
//   Games with '*' (Skyrim SE, Fallout 4, ...) list every non-primary plugin
//   in load order, active ones with a leading '*'. Games by file time
//   (Oblivion, Fallout 3, New Vegas, Skyrim LE) list only the active plugins.
// - loadorder.txt is UTF-8, CRLF, the same header, every plugin in order.
// Plugin names are compared ignoring case, as the games do.
#pragma once

#include <string>
#include <string_view>
#include <vector>

namespace mo2r::bethesda
{

enum class PluginsTxtStyle
{
  Asterisk,   // '*' marks the active plugins; all non-primary plugins listed
  ActiveOnly  // only the active plugins, no marker
};

struct PluginState
{
  std::wstring name;
  bool active = false;
};

struct WrittenList
{
  std::string bytes;
  // names the code page can't hold: written as an empty line, as MO2 does,
  // and reported so the user can rename them
  std::vector<std::wstring> unencodable;
};

inline constexpr std::string_view MO2Header =
    "# This file was automatically generated by Mod Organizer.\r\n";

// plugins.txt from the plugins in load order; primary plugins are left out in
// the Asterisk style (the game loads them anyway)
WrittenList writePluginsTxt(const std::vector<PluginState>& order,
                            const std::vector<std::wstring>& primaryPlugins,
                            PluginsTxtStyle style);

// loadorder.txt from the plugins in load order (all of them, UTF-8)
std::string writeLoadOrderTxt(const std::vector<PluginState>& order);

// the entries of a plugins.txt: comments and blank lines skipped, the '*'
// removed (Asterisk style: active = had '*'; ActiveOnly: all active). Lines
// are decoded from the ANSI code page. Duplicates (ignoring case) keep the
// first.
std::vector<PluginState> readPluginsTxt(std::string_view bytes, PluginsTxtStyle style);

// the names of a loadorder.txt (UTF-8), comments and blank lines skipped,
// duplicates (ignoring case) dropped
std::vector<std::wstring> readLoadOrderTxt(std::string_view bytes);

bool sameName(std::wstring_view a, std::wstring_view b);

// the load order MO2 is given: the primary plugins, then the listed ones
// (each once, primary ones skipped), then the present plugins no list placed,
// by name (ignoring case, then as written) so they're in the same order on
// every read. MO2's own plugins left those in whatever order the plugin list
// had them, which changes between runs.
std::vector<std::wstring> completeLoadOrder(const std::vector<std::wstring>& primary,
                                            const std::vector<std::wstring>& listed,
                                            const std::vector<std::wstring>& present);

}  // namespace mo2r::bethesda
